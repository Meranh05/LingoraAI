export function translate(
  locale: Locale,
  key: string,
  values: Record<string, string | number> = {},
) {
  const template = messages[locale][key] ?? messages.vi[key] ?? key;
  return Object.entries(values).reduce(
    (result, [name, value]) =>
      result.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

